// Compile contracts/*.cash into contracts/*.json artifacts, write the compact
// module src/tx/artifacts.js used at runtime, and print the sizes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compileString } from 'cashc';
import { asmToBytecode } from '@cashscript/utils';
import { binToHex } from '@bitauth/libauth';

const root = fileURLToPath(new URL('../', import.meta.url));
const compact = {};

for (const name of ['BoxOffice', 'Escrow']) {
  const source = readFileSync(`${root}contracts/${name}.cash`, 'utf8');
  const artifact = compileString(source);
  // Drop the volatile timestamp so rebuilding an unchanged contract is a no-op.
  delete artifact.updatedAt;
  writeFileSync(`${root}contracts/${name}.json`, `${JSON.stringify(artifact, null, 2)}\n`);
  const bytecode = asmToBytecode(artifact.bytecode);
  compact[name] = {
    contractName: artifact.contractName,
    compiler: `${artifact.compiler.name} ${artifact.compiler.version}`,
    constructorInputs: artifact.constructorInputs,
    abi: artifact.abi,
    bytecodeHex: binToHex(bytecode),
  };
  console.log(`${name}: ${bytecode.length} bytes of contract bytecode (before constructor pushes), ${artifact.abi.length} functions`);
}

writeFileSync(
  `${root}src/tx/artifacts.js`,
  `// Generated by scripts/compile.js from contracts/*.cash. Do not edit.\n` +
    `export const BoxOfficeArtifact = ${JSON.stringify(compact.BoxOffice, null, 2)};\n\n` +
    `export const EscrowArtifact = ${JSON.stringify(compact.Escrow, null, 2)};\n`,
);
