// Regression cases for the screening room's answer pipeline
// (worker/lib/room-faq.js). Plain data; the runner lives elsewhere.
//
// - match: the question must be answered with entry `id` (a botOk faq or room
//   entry), never a refusal or the fallback. The first block holds the honest
//   questions a too-broad filter would refuse; keep them first.
// - refuse: the question must get the refusal entry `refusal-${kind}`:
//   'secret' (hard-secret filter: 12+ BIP39 words, WIF, xprv/xpub, any 64-hex
//   run; never sent to a model, never logged), 'demand' (imperatives such as
//   "send me", "refund me", "confirm my refund", "promise a refund"), 'price'
//   (market price talk), 'seed' (sharing or recovering a seed or key),
//   'complaint' (a complaint that no help entry matches).
// - fallback: the question must get the fallback entry. These are run with
//   the word matcher only; a model (Phase C) may answer an honest Chinese
//   question, but never a money entry the matcher does not agree with.
// - launch: questions that get the fallback today because the answer they
//   need is hidden (botOk false) until launch; room-match.test.js checks that
//   each one reaches entry `id` once the launch-day answers are shown. When
//   launch shows them, move these questions from fallback to match.
//
// The key-shaped strings are shapes only: the WIF and xprv are random base58
// with no valid checksum, the 12-word phrases are the public BIP39 test
// vectors, and the 64-hex run is the Bitcoin Cash genesis block hash. In the
// blind questions, KwDiBf89... is the well-known WIF of private key 1; the
// other WIF-shaped strings, the 12 words after each "my seed is" and the
// bitcoincash: strings have no valid checksum (one is cut short).
//
// The blocks marked "Blind questions" are graded train sets A to E: questions
// guests and judges typed, word for word, with the outcome the grader expected.

